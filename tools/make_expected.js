// Writes docs/js/expected.js: the hashes a correct engine + model must reproduce.
'use strict';
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const E = require(path.join(root, 'docs/js/engine.js'));
const S = require(path.join(root, 'docs/js/selfcheck.js'));
const buf = fs.readFileSync(path.join(root, 'docs/assets/brain.bin'));
const model = E.createModel(new Uint8Array(buf.buffer, buf.byteOffset, buf.byteLength));
const r = S.run(E, model, 12);
const out = { engine: E.ENGINE_ID, model: model.id, modelBytes: buf.length, selfcheck: r.hash, selfcheckGames: r.games };
fs.writeFileSync(path.join(root, 'docs/js/expected.js'), '/* generated by tools/make_expected.js */\nwindow.CAPMON_EXPECTED = ' + JSON.stringify(out, null, 2) + ';\n');
console.log(JSON.stringify(Object.assign({ ms: r.ms, rounds: r.rounds }, out)));
